public class operators {
    public static void main(String[] args) {
        int a=5,b=6;
        System.out.println("arthemetic operators");
        System.out.println(a+b);
        System.out.println(a-b);
        System.out.println(a*b);
        System.out.println(a%b);
        System.out.println("unary operators");
        System.out.println(a++);
        System.out.println(++a);
        System.out.println(a);
        System.out.println(--a);
        System.out.println(a--);
    }
    
}
